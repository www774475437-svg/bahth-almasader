/// تصنيف الكتاب حسب عنوانه
String uthaymeenCategory(String t) {
  bool has(List<String> ws) => ws.any(t.contains);
  if (t.startsWith('تفسير') || has(['أصول في التفسير', 'مقدمة التفسير'])) return 'التفسير وعلومه';
  if (has(['فتاوى', 'لقاء', 'الباب المفتوح', 'نور على الدرب', 'سؤال', 'أسئلة', 'الكنز الثمين'])) {
    return 'الفتاوى واللقاءات';
  }
  if (has([
    'عقيدة', 'العقيدة', 'التوحيد', 'الواسطية', 'السفارينية', 'التدمرية', 'الحموية', 'لمعة',
    'القواعد المثلى', 'أسماء الله', 'ثلاثة الأصول', 'كشف الشبهات', 'القضاء والقدر', 'منهاج أهل السنة',
    'الإبداع'
  ])) {
    return 'العقيدة';
  }
  if (has(['رياض الصالحين', 'الأربعين', 'بلوغ المرام', 'البيقونية', 'مصطلح', 'حديث جابر'])) {
    return 'الحديث وعلومه';
  }
  if (has(['ألفية', 'مغني اللبيب', 'الأصول من علم الأصول'])) return 'الأصول واللغة';
  if (has([
    'الممتع', 'الكافي', 'زاد المستقنع', 'الفرائض', 'فقه', 'الصيام', 'الحج', 'الطهارة', 'الصلاة', 'الزكاة',
    'الحيض', 'الأضحية', 'المسح', 'الدماء', 'الوضوء', 'سجود السهو', 'المداينة', 'الذهب', 'الحجاب', 'الزواج',
    'العمرة', 'مناسك', 'رمضان', 'قنوت', 'الحلي', 'الأحكام الفقهية'
  ])) {
    return 'الفقه';
  }
  return 'رسائل ودروس وآداب';
}

